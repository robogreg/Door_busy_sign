// Generates firmware/src/broker/google_roots.h from a Mozilla CA bundle (certifi).
// Usage: node tools/gen_google_roots.js <path-to-cacert.pem>
// Pins the roots that Google endpoints (script.google.com,
// script.googleusercontent.com) chain to.
const fs = require("fs");
const path = require("path");

const src = process.argv[2];
if (!src) {
  console.error("usage: node tools/gen_google_roots.js <cacert.pem>");
  process.exit(1);
}
const wanted = ["GTS Root R1", "GTS Root R2", "GTS Root R3", "GTS Root R4", "GlobalSign ECC Root CA - R4"];
const text = fs.readFileSync(src, "utf8");
const blocks = text.split(/\n(?=# Issuer:)/);
const found = [];
let out = "// Generated by tools/gen_google_roots.js. Do not edit.\n";
out += "// Source: " + path.basename(src) + " (Mozilla CA bundle via certifi)\n#pragma once\n\n";
out += "static const char kGoogleRootsPem[] =\n";
for (const name of wanted) {
  const b = blocks.find((x) => x.includes('# Label: "' + name + '"'));
  if (!b) continue;
  const pem = b.match(/-----BEGIN CERTIFICATE-----[\s\S]+?-----END CERTIFICATE-----/)[0];
  out += "    // " + name + "\n";
  for (const line of pem.split("\n")) out += '    "' + line.trim() + '\\n"\n';
  found.push(name);
}
out += "    ;\n";
const dst = path.join(__dirname, "..", "firmware", "src", "broker", "google_roots.h");
fs.mkdirSync(path.dirname(dst), { recursive: true });
fs.writeFileSync(dst, out);
console.log("wrote " + dst + " with: " + found.join(", "));
const missing = wanted.filter((w) => !found.includes(w));
if (missing.length) console.log("not in bundle: " + missing.join(", "));
